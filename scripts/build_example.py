"""Build the hosted no-account example (docs/try/data.js) from app/sample/.

    npm run build:example     (or: python3 scripts/build_example.py)

Writes docs/try/data.js and docs/.nojekyll (GitHub Pages runs Jekyll from docs/
otherwise and drops files it considers private).
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
S = ROOT / "app" / "sample"


def rows(name, numeric):
    with open(S / name) as f:
        out = list(csv.DictReader(f))
    for r in out:
        for k in numeric:
            r[k] = float(r[k]) if "." in r[k] else int(r[k])
    return out


apps = rows("applications.csv", ["requested_monthly_volume", "years_in_business", "prior_processor_flag", "chargeback_history_bps"])
dec = {r["application_id"]: r for r in rows("decisions.csv", ["risk_score", "reserve_pct"])}
cats = {r["category_code"]: r for r in rows("categories.csv", ["base_risk"])}
for a in apps:
    d = dec[a["application_id"]]
    a.update({"decision": d["decision"], "risk_score": d["risk_score"], "decline_reason": d["decline_reason"],
              "reserve_pct": d["reserve_pct"], "base_risk": cats[a["category_code"]]["base_risk"]})
data = {
    "apps": apps,
    "cfpb": rows("cfpb_monthly.csv", ["complaint_count", "pct_monetary_relief", "pct_timely_response"]),
    "ai": json.loads((S / "ai.json").read_text()),
}
(DOCS / "try").mkdir(parents=True, exist_ok=True)
(DOCS / "try" / "data.js").write_text("/* Generated by scripts/build_example.py from app/sample/. */\nwindow.MRU = "
                                      + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
(DOCS / ".nojekyll").write_text("")
print("docs/try/data.js written;", len(apps), "applications,", len(data["ai"]["notes"]), "notes,",
      len(data["ai"]["ask"]), "answers; docs/.nojekyll written")
